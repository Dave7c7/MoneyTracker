import path from 'node:path';

import type { NextConfig } from 'next';

import { loadDotEnv } from '@moneytracker/db';

loadDotEnv();

/**
 * The security headers required by `rules/security.md`.
 *
 * The CSP allows inline styles because Recharts and Next.js inject them, and
 * allows unsafe-eval only in development.
 */
const securityHeaders = [
  { key: 'X-Content-Type-Options', value: 'nosniff' },
  { key: 'X-Frame-Options', value: 'DENY' },
  { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
  { key: 'X-DNS-Prefetch-Control', value: 'off' },
  { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=()' },
  {
    key: 'Content-Security-Policy',
    value: [
      "default-src 'self'",
      `script-src 'self' 'unsafe-inline'${process.env.NODE_ENV === 'development' ? " 'unsafe-eval'" : ''}`,
      "style-src 'self' 'unsafe-inline'",
      "img-src 'self' data: blob:",
      "font-src 'self' data:",
      "connect-src 'self'",
      "object-src 'none'",
      "base-uri 'self'",
      "form-action 'self'",
      "frame-ancestors 'none'",
    ].join('; '),
  },
];

const nextConfig: NextConfig = {
  // The workspace packages ship TypeScript sources.
  transpilePackages: ['@moneytracker/core', '@moneytracker/db'],
  // Trace from the monorepo root so the workspace packages are included.
  outputFileTracingRoot: path.join(import.meta.dirname, '../../'),
  output: 'standalone',
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: '/:path*',
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
